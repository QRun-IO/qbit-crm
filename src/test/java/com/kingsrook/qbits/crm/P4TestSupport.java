package com.kingsrook.qbits.crm;


import com.kingsrook.qqq.backend.core.exceptions.QException;
import com.kingsrook.qqq.backend.core.model.actions.tables.insert.InsertInput;
import com.kingsrook.qqq.backend.core.model.data.QRecord;
import com.kingsrook.qqq.backend.core.model.metadata.QAuthenticationType;
import com.kingsrook.qqq.backend.core.model.metadata.QBackendMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.QInstance;
import com.kingsrook.qqq.backend.core.model.metadata.authentication.QAuthenticationMetaData;
import com.kingsrook.qqq.backend.core.modules.backend.implementations.memory.MemoryBackendModule;
import com.kingsrook.qqq.backend.core.modules.backend.implementations.memory.MemoryRecordStore;


/*******************************************************************************
 ** Isolated host instances and fixture inserts, without bypassing actions under test.
 *******************************************************************************/
final class P4TestSupport
{
   /*******************************************************************************
    ** Utility class.
    *******************************************************************************/
   private P4TestSupport()
   {
   }


   /*******************************************************************************
    ** Build a host without CRM, ready for configuration-specific production.
    *******************************************************************************/
   static QInstance host()
   {
      QInstance instance = new QInstance();
      instance.withInstanceDefaultAuthentication(new QAuthenticationMetaData().withName("anonymous").withType(QAuthenticationType.FULLY_ANONYMOUS));
      instance.addBackend(new QBackendMetaData().withName("memory").withBackendType(MemoryBackendModule.class));
      return (instance);
   }


   /*******************************************************************************
    ** Fixture storage intentionally avoids business side effects.
    *******************************************************************************/
   static void seed(String table, QRecord... rows) throws QException
   {
      MemoryRecordStore.getInstance().insert(new InsertInput(table).withRecords(java.util.List.of(rows)), false);
   }
}
