package com.kingsrook.qbits.crm.deals;


import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import liquibase.Liquibase;
import liquibase.database.jvm.JdbcConnection;
import liquibase.resource.ClassLoaderResourceAccessor;
import org.junit.jupiter.api.Test;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;


/*******************************************************************************
 ** Upgrade an existing catalog without changing prices or product identities.
 *******************************************************************************/
class ProductCatalogMigrationTest
{
   /*******************************************************************************
    ** The real additive changeset preserves priced rows and permits unpriced
    ** products while enforcing non-null slug uniqueness.
    *******************************************************************************/
   @Test
   void upgradesPopulatedCatalog() throws Exception
   {
      try(Connection connection = DriverManager.getConnection("jdbc:h2:mem:catalog_" + UUID.randomUUID() + ";MODE=PostgreSQL"))
      {
         connection.createStatement().execute("CREATE TABLE crm_product (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(250) NOT NULL, unit_price DECIMAL(20,6) NOT NULL)");
         connection.createStatement().execute("INSERT INTO crm_product(id,name,unit_price) VALUES (42,'Existing product',77.25)");
         try(Liquibase liquibase = new Liquibase("db/liquibase/qbit-crm/crm-product-catalog.changelog.sql",
            new ClassLoaderResourceAccessor(), new JdbcConnection(connection)))
         {
            liquibase.update();
            liquibase.update();
            try(var result = connection.createStatement().executeQuery("SELECT id,unit_price FROM crm_product"))
            {
               assertThat(result.next()).isTrue();
               assertThat(result.getInt("id")).isEqualTo(42);
               assertThat(result.getBigDecimal("unit_price")).isEqualByComparingTo("77.25");
            }
            connection.createStatement().execute("INSERT INTO crm_product(name,slug) VALUES ('Informational','info')");
            connection.createStatement().execute("INSERT INTO crm_product(name) VALUES ('No slug one'),('No slug two')");
            assertThatThrownBy(() -> connection.createStatement().execute("INSERT INTO crm_product(name,slug) VALUES ('Duplicate','info')"))
               .isInstanceOf(SQLException.class);
            try(var result = connection.createStatement().executeQuery("SELECT unit_price FROM crm_product WHERE slug='info'"))
            {
               assertThat(result.next()).isTrue();
               assertThat(result.getBigDecimal(1)).isNull();
            }
         }
      }
   }
}
